    plt.ylabel("Cumulative Probability")
    plt.title("CDF of Position Error")
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.show()

    print("Baseline RMSE:", np.sqrt(np.mean(base_sorted**2)))
