NUM_CLASSES_EMB = 32

class DepthCorrectionNet(nn.Module):
    def __init__(self, n_cls_emb=NUM_CLASSES_EMB):
        super().__init__()
        self.cls_emb = nn.Embedding(256, n_cls_emb)  # safe upper bound

        self.mlp = nn.Sequential(
            nn.Linear(10 + n_cls_emb, 128),
            nn.ReLU(),
            nn.Linear(128, 128),
            nn.ReLU(),
            nn.Linear(128, 1)  # delta_z
        )

    def forward(self, x_num, cls_ids):
        emb = self.cls_emb(cls_ids)
        x = torch.cat([x_num, emb], dim=-1)
        dz = self.mlp(x).squeeze(-1)
        return dz

def make_numeric_features(rec):
    # normalized bbox features
    cx = rec["cx"] / rec["W"]
    cy = rec["cy"] / rec["H"]
    bw = (rec["x2"] - rec["x1"]) / rec["W"]
    bh = (rec["y2"] - rec["y1"]) / rec["H"]

    # lidar stats
    z_mean = rec["z_mean"]
    z_std  = rec["z_std"]
    npts   = rec["npts"]

    # compress npts (log scale)
    npts_log = np.log1p(npts) / 5.0

    # add a few stabilizers
    conf = rec["conf"]
    inv_std = 1.0 / (z_std + 1e-3)

    # 10 numeric features
    return np.array([cx, cy, bw, bh, conf, z_mean, z_std, inv_std, npts_log, 1.0], dtype=np.float32)

