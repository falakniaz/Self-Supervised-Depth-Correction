@torch.no_grad()
def refine_records_with_capacity_model(model, records_in):
    model.eval()
    out = []

    for r in records_in:
        x = torch.from_numpy(make_numeric_features(r)).float().to(DEVICE).unsqueeze(0)
        cls = torch.tensor([r["cls"]], dtype=torch.long, device=DEVICE)
        dz = float(model(x, cls)[0].detach().cpu())
        z_ref = float(r["z_mean"]) + dz

        # Numpy version of the same world transform for evaluation.
        uvzw = np.array([
            float(r["cx"]) * z_ref,
            float(r["cy"]) * z_ref,
            z_ref,
            1.0
        ], dtype=np.float64)
        imu_h = np.asarray(T_cam2_imu, dtype=np.float64) @ uvzw
        x_imu, y_imu, z_imu = imu_h[:3]
        yaw = float(r["yaw"])
        cy = np.cos(yaw)
        sy = np.sin(yaw)
        rel_enu = np.array([
            cy * x_imu - sy * y_imu,
            sy * x_imu + cy * y_imu,
            z_imu
        ], dtype=np.float64)
        world_ref = np.asarray(r["ego_enu"], dtype=np.float64) + rel_enu

        rr = dict(r)
        rr["dz"] = dz
        rr["z_ref"] = z_ref
        rr["world_ref"] = world_ref.astype(np.float32)
        out.append(rr)

    return out


def cv_error(pa, pb, pc):
    return float(np.linalg.norm(pc - (2.0 * pb - pa)))


def velocity_change_metric(pa, pb, pc, dt):
    # This exactly matches the current notebook's 3-frame "jerk_proxy".
    # It is a velocity-change / acceleration-proxy metric, not true jerk.
    v1 = (pb - pa) / dt
    v2 = (pc - pb) / dt
    return float(np.linalg.norm(v2 - v1))


def evaluate_capacity_model(model, records_in, eval_triples, dt):
    refined = refine_records_with_capacity_model(model, records_in)
    lookup = {(r["t"], r["tid"]): r for r in refined}

    cv_vals = []
    jerk_proxy_vals = []

    for a, b, c in eval_triples:
        ra = lookup.get((a["t"], a["tid"]))
        rb = lookup.get((b["t"], b["tid"]))
        rc = lookup.get((c["t"], c["tid"]))
        if ra is None or rb is None or rc is None:
            continue

        qa = np.asarray(ra["world_ref"], dtype=np.float64)
        qb = np.asarray(rb["world_ref"], dtype=np.float64)
        qc = np.asarray(rc["world_ref"], dtype=np.float64)

        cv_vals.append(cv_error(qa, qb, qc))
        jerk_proxy_vals.append(velocity_change_metric(qa, qb, qc, dt))

    if not cv_vals:
        raise RuntimeError("No aligned evaluation triples were found.")

    return {
        "CV Mean (m)": float(np.mean(cv_vals)),
        "CV Median (m)": float(np.median(cv_vals)),
        "Jerk Proxy Mean": float(np.mean(jerk_proxy_vals)),
        "Jerk Proxy Median": float(np.median(jerk_proxy_vals)),
        "N eval triples": int(len(cv_vals)),
    }

