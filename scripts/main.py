def plot_colored_trajectory_error(records_base, records_ref):
    from collections import defaultdict
    import numpy as np
    import matplotlib.pyplot as plt
    from matplotlib.collections import LineCollection

    # --- group by track id ---
    by_tid_base = defaultdict(list)
    by_tid_ref  = defaultdict(list)

    for r in records_base:
        by_tid_base[r["tid"]].append(r)
    for r in records_ref:
        by_tid_ref[r["tid"]].append(r)

    common_tids = list(set(by_tid_base.keys()) & set(by_tid_ref.keys()))
    if not common_tids:
        print("[ERROR] No common tids found between baseline and refined.")
        return

    # --- choose longest common track ---
    best_tid = max(common_tids, key=lambda tid: min(len(by_tid_base[tid]), len(by_tid_ref[tid])))

    b = sorted(by_tid_base[best_tid], key=lambda x: x["t"])
    r = sorted(by_tid_ref[best_tid],  key=lambda x: x["t"])

    n = min(len(b), len(r))
    if n < 4:
        print("[ERROR] Track too short for colored segments.")
        return

    # --- arrays ---
    B = np.stack([b[i]["world_lidar"] for i in range(n)], axis=0).astype(float)  # baseline positions
    R = np.stack([r[i]["world_ref"]   for i in range(n)], axis=0).astype(float)  # refined positions

    # error per time step
    err = np.linalg.norm(B - R, axis=1)

    # refined trajectory (E,N) for plotting
    points = R[:, :2]  # (East, North)

    # line segments (each segment is between consecutive points)
    segments = np.stack([points[:-1], points[1:]], axis=1)

    # color segments by midpoint error
    seg_err = 0.5 * (err[:-1] + err[1:])

    # --- build colored line collection ---
    lc = LineCollection(segments, array=seg_err, linewidth=3)

    # --- plot using fig/ax so legend/layout is clean ---
    fig, ax = plt.subplots(figsize=(7, 7))

    # baseline dashed
    ax.plot(B[:, 0], B[:, 1], "--", alpha=0.6, label="Baseline (LiDAR)")

    # refined colored line
    ax.add_collection(lc)

    # autoscale to include the line collection
    ax.autoscale()

    # start / end markers
    ax.scatter(points[0, 0],  points[0, 1],  marker="o", label="Start")
    ax.scatter(points[-1, 0], points[-1, 1], marker="x", label="End")

    # labels / title
    ax.set_xlabel("East (m)")
    ax.set_ylabel("North (m)")
    ax.set_title(f"Refined Trajectory Colored by Error (Track {best_tid})")
    ax.grid(True)
    ax.axis("equal")

    # colorbar
    cbar = fig.colorbar(lc, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label("Position Error (m)")

    # ✅ legend outside, no overlap/cropping
    #ax.legend(loc="upper inside", bbox_to_anchor=(1.02, 1.0), borderaxespad=0.0)

    # ✅ make room on the right for legend
    fig.subplots_adjust(right=0.78)

    plt.show()

    print(f"[INFO] Colored error trajectory for tid={best_tid}, points={n}")

