def read_lidar_bin(bin_path):
    pts = np.fromfile(bin_path, dtype=np.float32).reshape(-1, 4)
    xyz = pts[:, :3]
    xyz = xyz[xyz[:, 0] > 0]
    return xyz

def remove_ground_ransac(xyz):
    if len(xyz) < 50:
        return xyz
    try:
        X = xyz[:, :2]
        y = xyz[:, 2]
        ransac = linear_model.RANSACRegressor(
            estimator=linear_model.LinearRegression(),
            residual_threshold=0.15,
            max_trials=100,
            random_state=SEED,
        )
        ransac.fit(X, y)
        ground = ransac.inlier_mask_
        if ground is None:
            return xyz
        return xyz[~ground]
    except Exception:
        return xyz

def project_velo_to_image(bin_path, T_velo_cam2_proj, image_shape, remove_ground=REMOVE_GROUND):
    xyz = read_lidar_bin(bin_path)
    if remove_ground:
        xyz = remove_ground_ransac(xyz)

    if len(xyz) == 0:
        return np.zeros((3, 0), dtype=np.float32)

    xyzw = np.concatenate(
        [xyz, np.ones((len(xyz), 1), dtype=np.float32)],
        axis=1
    ).T

    cam = T_velo_cam2_proj @ xyzw
    z = cam[2]
    cam = cam[:, z > 0]

    if cam.shape[1] == 0:
        return np.zeros((3, 0), dtype=np.float32)

    cam[0] /= cam[2]
    cam[1] /= cam[2]

    h, w = image_shape[:2]
    valid = (
        (cam[0] >= 0) & (cam[0] < w) &
        (cam[1] >= 0) & (cam[1] < h)
    )
    return cam[:, valid].astype(np.float32)

def lidar_depth_stats(uvz, cx, cy, radius_px=ROI_RADIUS_PX):
    if uvz.shape[1] == 0:
        return np.nan, np.nan, 0

    u, v, z = uvz
    d2 = (u - cx) ** 2 + (v - cy) ** 2
    mask = d2 <= radius_px ** 2

    if np.any(mask):
        zs = z[mask]
        return float(np.mean(zs)), float(np.std(zs) + 1e-3), int(len(zs))

    idx = int(np.argmin(d2))
    return float(z[idx]), 5.0, 0

def timestamps_seconds(path):
    vals = []
    with open(path, "r") as f:
        for line in f:
            timepart = line.strip().split(" ")[-1]
            h, m, s = timepart.split(":")
            vals.append(float(h) * 3600 + float(m) * 60 + float(s))
    vals = np.asarray(vals, dtype=np.float64)
    return vals - vals[0]

def ego_enu_from_oxts(oxts, lat0, lon0, alt0):
    e, n, u = pm.geodetic2enu(
        oxts[0], oxts[1], oxts[2],
        lat0, lon0, alt0
    )
    return np.asarray([e, n, u], dtype=np.float32)

def yaw_from_oxts(oxts):
    return float(oxts[5])

def transform_uvz_numpy(uvz, T_cam2_imu):
    u, v, z = [float(x) for x in uvz]
    q = np.asarray([u * z, v * z, z, 1.0], dtype=np.float32)
    xyz = T_cam2_imu @ q
    return xyz[:3].astype(np.float32)

def imu_to_enu_numpy(xyz_imu, yaw):
    x, y, z = xyz_imu
    c, s = np.cos(yaw), np.sin(yaw)
    return np.asarray(
        [c*x - s*y, s*x + c*y, z],
        dtype=np.float32
    )

def world_from_record_depth_numpy(rec, z):
    local = transform_uvz_numpy(
        [rec["cx"], rec["cy"], z],
        rec["T_cam2_imu"]
    )
    return rec["ego_enu"] + imu_to_enu_numpy(local, rec["yaw"])

