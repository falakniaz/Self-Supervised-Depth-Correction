@torch.no_grad()
def measure_network_ms_per_frame(model, records, warmup=30, repeats=100):
    model.eval()

    by_frame = defaultdict(list)
    for r in records:
        by_frame[(r["seq"], r["t"])].append(r)

    batches = []
    for _, recs in sorted(by_frame.items()):
        X = torch.tensor(
            np.stack([make_numeric_features(r) for r in recs]),
            dtype=torch.float32,
            device=DEVICE,
        )
        C = torch.tensor(
            [r["cls"] for r in recs],
            dtype=torch.long,
            device=DEVICE,
        )
        batches.append((X, C))

    if not batches:
        return float("nan")

    for i in range(min(warmup, len(batches))):
        model(*batches[i % len(batches)])
    if torch.cuda.is_available():
        torch.cuda.synchronize()

    times = []
    for i in range(repeats):
        X, C = batches[i % len(batches)]
        if torch.cuda.is_available():
            torch.cuda.synchronize()
        t0 = time.perf_counter()
        model(X, C)
        if torch.cuda.is_available():
            torch.cuda.synchronize()
        times.append((time.perf_counter() - t0) * 1000.0)

    return float(np.mean(times))


