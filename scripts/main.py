# 6. Training + early stopping
# -----------------------------
def train_capacity_model(hidden_dims,
                         train_triples,
                         val_triples,
                         max_epochs=MAX_EPOCHS,
                         patience=PATIENCE,
                         lr=LEARNING_RATE,
                         seed=SEED):
    set_seed(seed)
    model = CapacityDepthCorrectionNet(hidden_dims=hidden_dims).to(DEVICE)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    best_val = np.inf
    best_state = None
    best_epoch = 0
    wait = 0
    history = []

    for epoch in range(1, max_epochs + 1):
        model.train()
        train_loss = []

        for a, b, c in train_triples:
            optimizer.zero_grad(set_to_none=True)
            loss, _, _, _ = loss_on_triple_capacity(model, a, b, c)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
            optimizer.step()
            train_loss.append(float(loss.detach().cpu()))

        model.eval()
        val_loss = []
        with torch.no_grad():
            for a, b, c in val_triples:
                loss, _, _, _ = loss_on_triple_capacity(model, a, b, c)
                val_loss.append(float(loss.detach().cpu()))

        tr = float(np.mean(train_loss)) if train_loss else np.nan
        va = float(np.mean(val_loss)) if val_loss else np.nan
        history.append({"epoch": epoch, "train_loss": tr, "val_loss": va})

        print(
            f"hidden={hidden_dims} | epoch={epoch:03d} | "
            f"train={tr:.6f} | val={va:.6f}"
        )

        if np.isfinite(va) and va < best_val - 1e-6:
            best_val = va
            best_epoch = epoch
            best_state = copy.deepcopy(model.state_dict())
            wait = 0
        else:
            wait += 1

        if wait >= patience:
            print(f"Early stopping. Best epoch: {best_epoch}, best val: {best_val:.6f}")
            break

    if best_state is None:
        raise RuntimeError("Training produced no valid validation checkpoint.")

    model.load_state_dict(best_state)
    return model, pd.DataFrame(history), best_epoch, best_val

