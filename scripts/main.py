    # Info box
    text = (
        f"Baseline: RMSE={b_rmse:.3f}  MAE={b_mae:.3f}  P50={b_p50:.2f}  P90={b_p90:.2f}\n"
        f"Refined:  RMSE={r_rmse:.3f}  MAE={r_mae:.3f}  P50={r_p50:.2f}  P90={r_p90:.2f}\n"
        f"N={len(ref_err)}"
    )
    ax.text(0.02, 0.98, text, transform=ax.transAxes, ha="left", va="top",
            bbox=dict(boxstyle="round", alpha=0.15))

    ax.set_xlabel("Position Error (m)")
    ax.set_ylabel("Cumulative Probability")
    ax.set_title("CDF: Baseline vs Refined Error")
    ax.grid(True)
    ax.legend(loc="lower right")
