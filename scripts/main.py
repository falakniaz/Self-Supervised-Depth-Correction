# 6. Training + early stopping
# ------------------------------------------------------------
def train_ablation_variant(
    variant_name,
    config,
    train_triples,
    val_triples,
    hidden_dims=HIDDEN_DIMS,
    max_epochs=MAX_EPOCHS,
    patience=PATIENCE,
    lr=LEARNING_RATE,
    seed=SEED,
):
    # Same initialization seed for every variant.
    set_seed(seed)

    model = AblationDepthCorrectionNet(hidden_dims=hidden_dims).to(DEVICE)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    best_val = np.inf
    best_state = None
    best_epoch = 0
    wait = 0
    history = []

    for epoch in range(1, max_epochs + 1):
        # -----------------------
        # Train
        # -----------------------
        model.train()
        tr_total = []
        tr_temp = []
        tr_reg = []
        tr_anchor = []

        for a, b, c in train_triples:
            optimizer.zero_grad(set_to_none=True)

            L, Lt, Lr, La = loss_on_triple_ablation(
                model, a, b, c,
                use_ego_motion=config["use_ego_motion"],
                w_temp=config["w_temp"],
                w_reg=config["w_reg"],
                w_anchor=config["w_anchor"],
            )

            L.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), GRAD_CLIP)
            optimizer.step()

            tr_total.append(float(L.detach().cpu()))
            tr_temp.append(float(Lt.detach().cpu()))
            tr_reg.append(float(Lr.detach().cpu()))
            tr_anchor.append(float(La.detach().cpu()))

        # -----------------------
        # Validation
        # -----------------------
        model.eval()
        va_total = []
        va_temp = []
        va_reg = []
        va_anchor = []

        with torch.no_grad():
            for a, b, c in val_triples:
                L, Lt, Lr, La = loss_on_triple_ablation(
                    model, a, b, c,
                    use_ego_motion=config["use_ego_motion"],
                    w_temp=config["w_temp"],
                    w_reg=config["w_reg"],
                    w_anchor=config["w_anchor"],
                )

                va_total.append(float(L.detach().cpu()))
                va_temp.append(float(Lt.detach().cpu()))
                va_reg.append(float(Lr.detach().cpu()))
                va_anchor.append(float(La.detach().cpu()))

        tr = float(np.mean(tr_total)) if tr_total else np.nan
        va = float(np.mean(va_total)) if va_total else np.nan

        history.append({
            "epoch": epoch,
            "train_loss": tr,
            "val_loss": va,
            "train_temp": float(np.mean(tr_temp)) if tr_temp else np.nan,
            "train_reg": float(np.mean(tr_reg)) if tr_reg else np.nan,
            "train_anchor": float(np.mean(tr_anchor)) if tr_anchor else np.nan,
            "val_temp": float(np.mean(va_temp)) if va_temp else np.nan,
            "val_reg": float(np.mean(va_reg)) if va_reg else np.nan,
            "val_anchor": float(np.mean(va_anchor)) if va_anchor else np.nan,
        })

        print(
            f"{variant_name:24s} | epoch={epoch:03d} | "
            f"train={tr:.6f} | val={va:.6f}"
        )

        if np.isfinite(va) and va < best_val - 1e-6:
            best_val = va
            best_epoch = epoch
            best_state = copy.deepcopy(model.state_dict())
            wait = 0
        else:
            wait += 1

        if wait >= patience:
            print(
                f"Early stopping: {variant_name}. "
                f"Best epoch={best_epoch}, best val={best_val:.6f}"
            )
            break

    if best_state is None:
        raise RuntimeError(f"No valid checkpoint for {variant_name}.")

    model.load_state_dict(best_state)
    return model, pd.DataFrame(history), best_epoch, best_val

