def scan_text_file(path):
    try:
        text = path.read_text(errors="ignore")
    except Exception:
        return

    # Detect sequence + frame + split on the same line.
    for line in text.splitlines():
        seq = normalize_seq(line)
        if not seq:
            continue

        toks = re.split(r"[^A-Za-z]+", line.lower())
        splits = [normalize_split(t) for t in toks]
        splits = [s for s in splits if s]
        if len(set(splits)) != 1:
            continue

        split = splits[0]

        # Prefer 10-digit KITTI frame IDs if present.
        nums = re.findall(r"(?<!\d)(\d{6,10})(?!\d)", line)
        for n in nums:
            # Do not confuse date/drive with frame if possible.
            try:
                f = int(n)
            except Exception:
                continue

            # A KITTI frame index in these sequences is usually much smaller
            # than a date-like number.
            if f < 100000:
                add_evidence(seq, f, split, path, "text_artifact")

def scan_json(path):
    try:
        obj = json.loads(path.read_text(errors="ignore"))
    except Exception:
        return

    # Easiest robust method: serialize lines and scan.
    text = json.dumps(obj)
    for seq_date, seq_drive, _ in SEQUENCES:
        seq = canonical_seq(seq_date, seq_drive)
        if seq not in text:
            continue

    # Also handle split-key structures.
    if isinstance(obj, dict):
        for key, vals in obj.items():
            split = normalize_split(key)
            if not split or not isinstance(vals, list):
                continue

            for item in vals:
                s = json.dumps(item)
                seq = normalize_seq(s)
                nums = re.findall(r"(?<!\d)(\d{1,10})(?!\d)", s)

                for n in nums:
                    f = int(n)
                    if seq and f < 100000:
                        add_evidence(seq, f, split, path, "json_manifest")

def scan_ipynb(path):
    try:
        nb = json.loads(path.read_text(errors="ignore"))
    except Exception:
        return

    for i, cell in enumerate(nb.get("cells", [])):
        text = "".join(cell.get("source", []))

        # We only record explicit lines containing a target sequence,
        # a split word, and a plausible frame index.
        for line in text.splitlines():
            seq = normalize_seq(line)
            if not seq:
                continue

            toks = re.split(r"[^A-Za-z]+", line.lower())
            splits = [normalize_split(t) for t in toks]
            splits = [s for s in splits if s]

            if len(set(splits)) != 1:
                continue

            nums = re.findall(r"(?<!\d)(\d{1,10})(?!\d)", line)
            for n in nums:
                f = int(n)
                if f < 100000:
                    add_evidence(
                        seq, f, splits[0],
                        f"{path}::cell{i}",
                        "notebook_code"
                    )

