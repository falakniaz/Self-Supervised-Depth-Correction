def make_bev_canvas(canvas_h, canvas_w, imu_points_xyz, sf=12):
    canvas = np.zeros((canvas_h, canvas_w, 3), dtype=np.uint8)

    # ego vehicle at bottom center
    ego_center = (canvas_w//2, int(canvas_h*0.95))
    ego_x1, ego_y1 = ego_center[0] - 5, ego_center[1] - 10
    ego_x2, ego_y2 = ego_center[0] + 5, ego_center[1] + 10
    cv2.rectangle(canvas, (ego_x1, ego_y1), (ego_x2, ego_y2), (0,255,0), -1)

    # objects
    for val in imu_points_xyz:
        obj_center = (ego_center[0] - sf*int(np.round(val[1])),
                      ego_center[1] - sf*int(np.round(val[0])))

        obj_x1, obj_y1 = obj_center[0] - 5, obj_center[1] - 10
        obj_x2, obj_y2 = obj_center[0] + 5, obj_center[1] + 10
        cv2.rectangle(canvas, (obj_x1, obj_y1), (obj_x2, obj_y2), (255,0,0), -1)

    return canvas

