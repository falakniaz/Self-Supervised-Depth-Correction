def train_model(triples_train, triples_val, w_temp, w_anchor, w_reg, epochs=3, lr=1e-3):
    m = DepthCorrectionNet().to(DEVICE)
    opt = optim.Adam(m.parameters(), lr=lr)

    def step(tr_list, train=True):
        if train: m.train()
        else: m.eval()
        total = 0.0; n=0
        for (a,b,c) in tr_list:
            if train: opt.zero_grad()
            L, _ = loss_on_triple(m, a,b,c, w_temp=w_temp, w_anchor=w_anchor, w_reg=w_reg)
            if train:
                L.backward()
                opt.step()
            total += float(L.detach().cpu().item()); n += 1
        return total/max(n,1)

    for ep in range(epochs):
        tr = step(train_tr, True)
        va = step(val_tr, False)
        print(f"ep {ep+1}/{epochs} train {tr:.4f} val {va:.4f}")

    return m

