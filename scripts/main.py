def plot_position_error(records_base, records_ref, top_k=5):
    from collections import defaultdict
    import numpy as np
    import matplotlib.pyplot as plt

    # Group by track id
    by_tid_base = defaultdict(list)
    by_tid_ref  = defaultdict(list)

    for r in records_base:
        by_tid_base[r["tid"]].append(r)
    for r in records_ref:
        by_tid_ref[r["tid"]].append(r)

    # Select top-K longest common tracks
    lens = [(tid, len(lst)) for tid, lst in by_tid_base.items() if tid in by_tid_ref]
    lens = sorted(lens, key=lambda x: x[1], reverse=True)[:top_k]

    plt.figure(figsize=(8,5))

    for tid, _ in lens:
        b = sorted(by_tid_base[tid], key=lambda x: x["t"])
        r = sorted(by_tid_ref[tid],  key=lambda x: x["t"])

        # Align by minimum length (safe matching)
        min_len = min(len(b), len(r))

        times = np.array([b[i]["t"] for i in range(min_len)])

        B = np.stack([b[i]["world_lidar"] for i in range(min_len)], axis=0)
        R = np.stack([r[i]["world_ref"]   for i in range(min_len)], axis=0)

        # Euclidean error
        error = np.linalg.norm(B - R, axis=1)

        plt.plot(times, error, label=f"Track {tid}")

    plt.xlabel("Time (s)")
    plt.ylabel("Position Error (m)")
    plt.title(f"Position Error vs Time (Top-{top_k} Tracks)")
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

