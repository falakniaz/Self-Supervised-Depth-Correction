class CapacityDepthCorrectionNet(nn.Module):
    def __init__(self, hidden_dims=(128, 128), n_cls_emb=NUM_CLASSES_EMB):
        super().__init__()
        self.cls_emb = nn.Embedding(256, n_cls_emb)
        input_dim = 10 + n_cls_emb

        layers = []
        prev = input_dim
        for h in hidden_dims:
            layers += [nn.Linear(prev, h), nn.ReLU()]
            prev = h
        layers.append(nn.Linear(prev, 1))
        self.mlp = nn.Sequential(*layers)

    def forward(self, x_num, cls_ids):
        emb = self.cls_emb(cls_ids)
        x = torch.cat([x_num, emb], dim=-1)
        return self.mlp(x).squeeze(-1)


def count_parameters(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def approximate_linear_flops_per_object(hidden_dims, n_cls_emb=NUM_CLASSES_EMB):
    # Approximate FLOPs for Linear layers only: 2 * MACs.
    dims = [10 + n_cls_emb] + list(hidden_dims) + [1]
    macs = sum(dims[i] * dims[i + 1] for i in range(len(dims) - 1))
    return int(2 * macs)

# -----------------------------
# 4. Differentiable world transform
#    Fixes detach().cpu().item() in the original temporal loss.
# -----------------------------
def world_from_depth_torch(rec, z):
    dtype = z.dtype
    device = z.device

    u = torch.as_tensor(float(rec["cx"]), dtype=dtype, device=device)
    v = torch.as_tensor(float(rec["cy"]), dtype=dtype, device=device)
    one = torch.ones((), dtype=dtype, device=device)

    # Same uvz -> homogeneous xyz convention used by transform_uvz:
    # [u*z, v*z, z, 1]
    uvzw = torch.stack([u * z, v * z, z, one])
    T = torch.as_tensor(T_cam2_imu, dtype=dtype, device=device)
    imu_h = T @ uvzw
    imu_xyz = imu_h[:3]

    yaw = torch.as_tensor(float(rec["yaw"]), dtype=dtype, device=device)
    c = torch.cos(yaw)
    s = torch.sin(yaw)

    x, y, z_imu = imu_xyz[0], imu_xyz[1], imu_xyz[2]
    east = c * x - s * y
    north = s * x + c * y
    up = z_imu
    rel_enu = torch.stack([east, north, up])

    ego = torch.as_tensor(np.asarray(rec["ego_enu"]), dtype=dtype, device=device)
    return ego + rel_enu

# -----------------------------
# 5. Loss
# -----------------------------
def loss_on_triple_capacity(model, a, b, c,
                            w_temp=W_TEMP,
                            w_anchor=W_ANCHOR,
                            w_reg=W_REG):
    xa = torch.from_numpy(make_numeric_features(a)).float().to(DEVICE).unsqueeze(0)
    xb = torch.from_numpy(make_numeric_features(b)).float().to(DEVICE).unsqueeze(0)
    xc = torch.from_numpy(make_numeric_features(c)).float().to(DEVICE).unsqueeze(0)

    ca = torch.tensor([a["cls"]], dtype=torch.long, device=DEVICE)
    cb = torch.tensor([b["cls"]], dtype=torch.long, device=DEVICE)
    cc = torch.tensor([c["cls"]], dtype=torch.long, device=DEVICE)

    dza = model(xa, ca)[0]
    dzb = model(xb, cb)[0]
    dzc = model(xc, cc)[0]

    za = torch.as_tensor(float(a["z_mean"]), device=DEVICE) + dza
    zb = torch.as_tensor(float(b["z_mean"]), device=DEVICE) + dzb
    zc = torch.as_tensor(float(c["z_mean"]), device=DEVICE) + dzc

    # IMPORTANT: no detach() here; temporal loss remains differentiable.
    pa = world_from_depth_torch(a, za)
    pb = world_from_depth_torch(b, zb)
    pc = world_from_depth_torch(c, zc)

    pred_pc = 2.0 * pb - pa
    L_temp = torch.norm(pc - pred_pc, p=2)

    sa = max(float(a["z_std"]), 1e-3)
    sb = max(float(b["z_std"]), 1e-3)
    sc = max(float(c["z_std"]), 1e-3)
    L_anchor = ((dza / sa) ** 2 + (dzb / sb) ** 2 + (dzc / sc) ** 2) / 3.0

    L_reg = (dza ** 2 + dzb ** 2 + dzc ** 2) / 3.0
    total = w_temp * L_temp + w_anchor * L_anchor + w_reg * L_reg
    return total, L_temp, L_anchor, L_reg

