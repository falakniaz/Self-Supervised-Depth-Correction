def plot_error_vs_distance(records_base, records_ref, nbins=25, max_points=20000):
    from collections import defaultdict
    import numpy as np
    import matplotlib.pyplot as plt

    # group by tid
    by_tid_base = defaultdict(list)
    by_tid_ref  = defaultdict(list)

    for r in records_base:
        by_tid_base[r["tid"]].append(r)
    for r in records_ref:
        by_tid_ref[r["tid"]].append(r)

    common_tids = set(by_tid_base.keys()) & set(by_tid_ref.keys())
    if not common_tids:
        print("[ERROR] No common tids found.")
        return

    D = []
    E = []

    for tid in common_tids:
        b = sorted(by_tid_base[tid], key=lambda x: x["t"])
        r = sorted(by_tid_ref[tid],  key=lambda x: x["t"])

        n = min(len(b), len(r))
        if n < 3:
            continue

        # positions
        B = np.stack([b[i]["world_lidar"] for i in range(n)], axis=0).astype(float)
        R = np.stack([r[i]["world_ref"]   for i in range(n)], axis=0).astype(float)

        # ego positions (ENU)
        Ego = np.stack([r[i]["ego_enu"] for i in range(n)], axis=0).astype(float)

        # distance in XY plane (object relative to ego)
        dist = np.linalg.norm(R[:, :2] - Ego[:, :2], axis=1)

        # error
        err = np.linalg.norm(B - R, axis=1)

        D.append(dist)
        E.append(err)

    if not D:
        print("[ERROR] Not enough aligned points to plot.")
        return

    D = np.concatenate(D, axis=0)
    E = np.concatenate(E, axis=0)

    # downsample for cleaner scatter
    if D.shape[0] > max_points:
        idx = np.random.choice(D.shape[0], size=max_points, replace=False)
        D = D[idx]
        E = E[idx]

    # binning for mean curve
    edges = np.linspace(D.min(), D.max(), nbins + 1)
    centers = 0.5 * (edges[:-1] + edges[1:])

    mean_err = np.full(nbins, np.nan)
    for i in range(nbins):
        mask = (D >= edges[i]) & (D < edges[i+1])
        if np.any(mask):
            mean_err[i] = np.mean(E[mask])

    fig, ax = plt.subplots(figsize=(7, 5))

    ax.scatter(D, E, s=8, alpha=0.35, label="Samples")
    ax.plot(centers, mean_err, linewidth=2, label="Binned Mean Error")

    ax.set_title("Position Error vs Distance from Ego")
    ax.set_xlabel("Distance from Ego (m)")
    ax.set_ylabel("Position Error (m)")
    ax.grid(True, alpha=0.3)
    ax.legend()
    plt.tight_layout()
    plt.show()

    print(f"[INFO] Samples plotted: {len(D)}")
    print(f"[INFO] Error stats: mean={E.mean():.3f} m, p50={np.percentile(E,50):.3f} m, p90={np.percentile(E,90):.3f} m")

