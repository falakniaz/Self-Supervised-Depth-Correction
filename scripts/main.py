def loss_on_triple(model, a, b, c, w_temp=1.0, w_anchor=0.2, w_reg=0.01):
    # build inputs
    xa = torch.from_numpy(make_numeric_features(a)).to(DEVICE).unsqueeze(0)
    xb = torch.from_numpy(make_numeric_features(b)).to(DEVICE).unsqueeze(0)
    xc = torch.from_numpy(make_numeric_features(c)).to(DEVICE).unsqueeze(0)

    ca = torch.tensor([a["cls"]], dtype=torch.long, device=DEVICE)
    cb = torch.tensor([b["cls"]], dtype=torch.long, device=DEVICE)
    cc = torch.tensor([c["cls"]], dtype=torch.long, device=DEVICE)

    # predict depth corrections
    dza = model(xa, ca)[0]
    dzb = model(xb, cb)[0]
    dzc = model(xc, cc)[0]

    za = a["z_mean"] + dza
    zb = b["z_mean"] + dzb
    zc = c["z_mean"] + dzc

    # world points
    pa = torch.from_numpy(refined_world_from_record(a, za.detach().cpu().item())).to(DEVICE)
    pb = torch.from_numpy(refined_world_from_record(b, zb.detach().cpu().item())).to(DEVICE)
    pc = torch.from_numpy(refined_world_from_record(c, zc.detach().cpu().item())).to(DEVICE)

    # temporal constant-velocity (2nd order)
    pred_pc = 2.0 * pb - pa
    L_temp = torch.norm(pc - pred_pc, p=2)

    # anchor: keep dz small relative to lidar std (more freedom when std is big)
    sa = a["z_std"]; sb = b["z_std"]; sc = c["z_std"]
    L_anchor = (dza / (sa + 1e-3))**2 + (dzb / (sb + 1e-3))**2 + (dzc / (sc + 1e-3))**2
    L_anchor = L_anchor / 3.0

    # regularize dz
    L_reg = (dza**2 + dzb**2 + dzc**2) / 3.0

    return w_temp * L_temp + w_anchor * L_anchor + w_reg * L_reg, (L_temp.item(), L_anchor.item(), L_reg.item())

