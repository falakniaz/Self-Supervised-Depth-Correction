def make_grid(image_paths, cols=2):
    imgs = [cv2.cvtColor(cv2.imread(p), cv2.COLOR_BGR2RGB) for p in image_paths]
    # resize to same height
    h = min(im.shape[0] for im in imgs)
    resized = []
    for im in imgs:
        scale = h / im.shape[0]
        w = int(im.shape[1]*scale)
        resized.append(cv2.resize(im, (w,h)))

    rows = []
    for i in range(0, len(resized), cols):
        row = resized[i]
        for j in range(1, cols):
            if i+j < len(resized):
                row = np.hstack([row, resized[i+j]])
        rows.append(row)

    grid = rows[0]
    for r in rows[1:]:
        # pad widths if needed
        if r.shape[1] < grid.shape[1]:
            pad = np.zeros((r.shape[0], grid.shape[1]-r.shape[1], 3), dtype=r.dtype)
            r = np.hstack([r, pad])
        elif r.shape[1] > grid.shape[1]:
            pad = np.zeros((grid.shape[0], r.shape[1]-grid.shape[1], 3), dtype=grid.dtype)
            grid = np.hstack([grid, pad])
        grid = np.vstack([grid, r])
    return grid

