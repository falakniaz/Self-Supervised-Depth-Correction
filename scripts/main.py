# 8. Metrics
# ------------------------------------------------------------
def cv_error_np(pa, pb, pc):
    return float(np.linalg.norm(pc - (2.0 * pb - pa)))


def jerk_proxy_np(pa, pb, pc, dt):
    """
    Matches the current notebook's three-frame velocity-change metric.
    This is an acceleration/velocity-change proxy, not physical jerk.
    """
    v1 = (pb - pa) / dt
    v2 = (pc - pb) / dt
    return float(np.linalg.norm(v2 - v1))


def evaluate_variant(model, records_in, eval_triples, dt):
    refined = refine_records_global(model, records_in)
    lookup = {(r["t"], r["tid"]): r for r in refined}

    cv_vals = []
    jerk_vals = []
    dz_abs = []

    for a, b, c in eval_triples:
        ra = lookup.get((a["t"], a["tid"]))
        rb = lookup.get((b["t"], b["tid"]))
        rc = lookup.get((c["t"], c["tid"]))
        if ra is None or rb is None or rc is None:
            continue

        pa = np.asarray(ra["world_ref"], dtype=np.float64)
        pb = np.asarray(rb["world_ref"], dtype=np.float64)
        pc = np.asarray(rc["world_ref"], dtype=np.float64)

        cv_vals.append(cv_error_np(pa, pb, pc))
        jerk_vals.append(jerk_proxy_np(pa, pb, pc, dt))
        dz_abs.extend([
            abs(float(ra["dz"])),
            abs(float(rb["dz"])),
            abs(float(rc["dz"])),
        ])

    if not cv_vals:
        raise RuntimeError("No aligned evaluation triples were found.")

    return {
        "CV Mean (m)": float(np.mean(cv_vals)),
        "CV Median (m)": float(np.median(cv_vals)),
        "Jerk Proxy Mean": float(np.mean(jerk_vals)),
        "Jerk Proxy Median": float(np.median(jerk_vals)),
        "Mean |dz|": float(np.mean(dz_abs)) if dz_abs else np.nan,
        "P95 |dz|": float(np.percentile(dz_abs, 95)) if dz_abs else np.nan,
        "N eval triples": int(len(cv_vals)),
    }

