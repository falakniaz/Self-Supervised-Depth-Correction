@torch.no_grad()
def refine_records(model, records):
    model.eval()
    out = []
    for rec in records:
        x, cls = record_to_tensors(rec)
        dz = float(model(x.unsqueeze(0), cls.unsqueeze(0))[0].detach().cpu())
        rr = dict(rec)
        rr["dz"] = dz
        rr["z_ref"] = float(rec["z_mean"] + dz)
        rr["world_ref"] = world_from_record_depth_numpy(rr, rr["z_ref"])
        out.append(rr)
    return out

def cv_error(p0, p1, p2):
    return float(np.linalg.norm(p2 - (2.0*p1 - p0)))

def old_velocity_change_proxy(p0, p1, p2, dt):
    v1 = (p1 - p0) / dt
    v2 = (p2 - p1) / dt
    return float(np.linalg.norm(v2 - v1))

def true_jerk(p0, p1, p2, p3, dt):
    return float(
        np.linalg.norm(p3 - 3*p2 + 3*p1 - p0) / (dt ** 3)
    )

def eval_positions_from_lookup(base_records, pos_lookup, method_name):
    triples = build_triples(base_records)
    quads = build_quads(base_records)

    triple_rows = []
    for a, b, c in triples:
        ka = (a["track_key"], a["t"])
        kb = (b["track_key"], b["t"])
        kc = (c["track_key"], c["t"])
        if ka not in pos_lookup or kb not in pos_lookup or kc not in pos_lookup:
            continue

        p0 = np.asarray(pos_lookup[ka], dtype=np.float64)
        p1 = np.asarray(pos_lookup[kb], dtype=np.float64)
        p2 = np.asarray(pos_lookup[kc], dtype=np.float64)

        dt = float(b["dt_default"])
        triple_rows.append({
            "method": method_name,
            "seq": b["seq"],
            "track_key": b["track_key"],
            "center_t": b["t"],
            "cv": cv_error(p0, p1, p2),
            "velocity_change_proxy": old_velocity_change_proxy(p0, p1, p2, dt),
        })

    quad_rows = []
    for a, b, c, d in quads:
        keys = [
            (a["track_key"], a["t"]),
            (b["track_key"], b["t"]),
            (c["track_key"], c["t"]),
            (d["track_key"], d["t"]),
        ]
        if not all(k in pos_lookup for k in keys):
            continue

        p = [np.asarray(pos_lookup[k], dtype=np.float64) for k in keys]
        dt = float(b["dt_default"])
        quad_rows.append({
            "method": method_name,
            "seq": b["seq"],
            "track_key": b["track_key"],
            "center_t": c["t"],
            "true_jerk_m_s3": true_jerk(p[0], p[1], p[2], p[3], dt),
        })

    return pd.DataFrame(triple_rows), pd.DataFrame(quad_rows)

def summarize_metrics(df_triple, df_quad):
    if len(df_triple):
        cv_mean = float(df_triple["cv"].mean())
        cv_median = float(df_triple["cv"].median())
        cv_p90 = float(df_triple["cv"].quantile(0.90))
        proxy_mean = float(df_triple["velocity_change_proxy"].mean())
    else:
        cv_mean = cv_median = cv_p90 = proxy_mean = float("nan")

    if len(df_quad):
        jerk_mean = float(df_quad["true_jerk_m_s3"].mean())
        jerk_median = float(df_quad["true_jerk_m_s3"].median())
    else:
        jerk_mean = jerk_median = float("nan")

    return {
        "CV Mean (m)": cv_mean,
        "CV Median (m)": cv_median,
        "CV P90 (m)": cv_p90,
        "True Jerk Mean (m/s^3)": jerk_mean,
        "True Jerk Median (m/s^3)": jerk_median,
        "Old velocity-change proxy mean": proxy_mean,
        "N CV triples": len(df_triple),
        "N jerk quadruples": len(df_quad),
    }

def evaluate_model_on_records(model, records, method_name):
    refined = refine_records(model, records)
    pos = {
        (r["track_key"], r["t"]): r["world_ref"]
        for r in refined
    }
    tri, quad = eval_positions_from_lookup(records, pos, method_name)
    return summarize_metrics(tri, quad), tri, quad, refined

