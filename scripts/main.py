def make_numeric_features(rec):
    cx = rec["cx"] / rec["W"]
    cy = rec["cy"] / rec["H"]
    bw = (rec["x2"] - rec["x1"]) / rec["W"]
    bh = (rec["y2"] - rec["y1"]) / rec["H"]

    z_mean = rec["z_mean"]
    z_std = rec["z_std"]
    inv_std = 1.0 / (z_std + 1e-3)
    npts_log = np.log1p(rec["npts"]) / 5.0

    return np.asarray(
        [cx, cy, bw, bh, rec["conf"], z_mean, z_std, inv_std, npts_log, 1.0],
        dtype=np.float32,
    )

class DepthCorrectionNet(nn.Module):
    def __init__(self, hidden_dims=(64, 64), n_cls_emb=NUM_CLASS_EMB):
        super().__init__()
        self.hidden_dims = tuple(hidden_dims)
        self.cls_emb = nn.Embedding(256, n_cls_emb)

        layers = []
        in_dim = 10 + n_cls_emb
        for h in hidden_dims:
            layers.extend([nn.Linear(in_dim, h), nn.ReLU()])
            in_dim = h
        layers.append(nn.Linear(in_dim, 1))
        self.mlp = nn.Sequential(*layers)

    def forward(self, x_num, cls_ids):
        emb = self.cls_emb(cls_ids)
        x = torch.cat([x_num, emb], dim=-1)
        return self.mlp(x).squeeze(-1)

def count_params(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)

