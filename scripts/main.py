def contiguous_ranges(values):
    vals = sorted(set(int(v) for v in values))
    if not vals:
        return []

    out = []
    a = b = vals[0]
    for x in vals[1:]:
        if x == b + 1:
            b = x
        else:
            out.append((a, b))
            a = b = x
    out.append((a, b))
    return out

def format_ranges(values, pad=10):
    ranges = contiguous_ranges(values)
    if not ranges:
        return "UNKNOWN"

    pieces = []
    for a, b in ranges:
        if a == b:
            pieces.append(f"{a:0{pad}d}")
        else:
            pieces.append(f"{a:0{pad}d}-{b:0{pad}d}")
    return ", ".join(pieces)

def normalize_split(x):
    if x is None:
        return None

    s = str(x).strip().lower()
    aliases = {
        "train": "Train",
        "training": "Train",
        "tr": "Train",
        "val": "Validation",
        "valid": "Validation",
        "validation": "Validation",
        "dev": "Validation",
        "test": "Test",
        "testing": "Test",
        "te": "Test",
    }

    s2 = re.sub(r"[^a-z]", "", s)
    return aliases.get(s2)

