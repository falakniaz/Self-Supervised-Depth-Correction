def plot_trackwise_correction_magnitude(records_base, records_ref, top_k=20):
    from collections import defaultdict
    import numpy as np
    import matplotlib.pyplot as plt

    by_tid_base = defaultdict(list)
    by_tid_ref  = defaultdict(list)

    for r in records_base:
        by_tid_base[r["tid"]].append(r)
    for r in records_ref:
        by_tid_ref[r["tid"]].append(r)

    common_tids = list(set(by_tid_base.keys()) & set(by_tid_ref.keys()))
    if not common_tids:
        print("[ERROR] No common tids found.")
        return

    rows = []
    for tid in common_tids:
        b = sorted(by_tid_base[tid], key=lambda x: x["t"])
        r = sorted(by_tid_ref[tid],  key=lambda x: x["t"])

        n = min(len(b), len(r))
        if n < 3:
            continue

        B  = np.stack([b[i]["world_lidar"] for i in range(n)], axis=0).astype(float)
        RR = np.stack([r[i]["world_ref"]   for i in range(n)], axis=0).astype(float)

        corr = np.linalg.norm(B - RR, axis=1)  # correction magnitude per frame

        rmse_corr = float(np.sqrt(np.mean(corr**2)))
        mean_corr = float(np.mean(corr))
        p90_corr  = float(np.percentile(corr, 90))

        rows.append((tid, n, rmse_corr, mean_corr, p90_corr))

    if not rows:
        print("[ERROR] No valid tracks.")
        return

    # Sort by RMSE correction magnitude (largest changes first)
    rows.sort(key=lambda x: x[2], reverse=True)
    rows = rows[:top_k]

    tids = [str(x[0]) for x in rows]
    vals = [x[2] for x in rows]  # RMSE correction

    fig, ax = plt.subplots(figsize=(10, 4))
    ax.bar(tids, vals)

    ax.set_title(f"Track-wise Correction Magnitude (RMSE) — Top {len(rows)} Tracks")
    ax.set_xlabel("Track ID (tid)")
    ax.set_ylabel("Correction RMSE (m)")
    ax.grid(True, axis="y", alpha=0.3)

    plt.tight_layout()
    plt.show()

    print("tid | points | RMSE_corr | mean_corr | P90_corr")
    for tid, n, rmse_corr, mean_corr, p90_corr in rows:
        print(f"{tid:>3} | {n:>6} | {rmse_corr:>9.3f} | {mean_corr:>9.3f} | {p90_corr:>8.3f}")

