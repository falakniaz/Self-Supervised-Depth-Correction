def cv_error(pa, pb, pc):
    pred = 2*pb - pa
    return float(np.linalg.norm(pc - pred))

def vel_vec(pa, pb, dt=1.0):
    return (pb - pa) / dt

def jerk_proxy(pa, pb, pc, dt=1.0):
    v1 = vel_vec(pa, pb, dt)
    v2 = vel_vec(pb, pc, dt)
    return float(np.linalg.norm(v2 - v1))

