def run_epoch(tr_list, train=True):
    if train:
        model.train()
    else:
        model.eval()

    total = 0.0
    n = 0
    temps, anchors, regs = [], [], []

    for (a,b,c) in tr_list:
        if train:
            opt.zero_grad()

        L, parts = loss_on_triple(model, a,b,c, w_temp=1.0, w_anchor=0.3, w_reg=0.01)

        if train:
            L.backward()
            opt.step()

        total += float(L.detach().cpu().item())
        n += 1
        temps.append(parts[0]); anchors.append(parts[1]); regs.append(parts[2])

    return total/max(n,1), (np.mean(temps), np.mean(anchors), np.mean(regs))

