def cluster_bootstrap_improvement(
    baseline_df,
    proposed_df,
    metric_col,
    reps=BOOTSTRAP_REPS,
    seed=BOOTSTRAP_SEED,
):
    b = baseline_df[["track_key", "center_t", metric_col]].copy()
    p = proposed_df[["track_key", "center_t", metric_col]].copy()

    merged = b.merge(
        p,
        on=["track_key", "center_t"],
        suffixes=("_base", "_prop"),
        how="inner",
    )

    tracks = sorted(merged["track_key"].unique().tolist())
    if len(tracks) == 0:
        return {
            "n_tracks": 0,
            "point_improvement_pct": np.nan,
            "ci_low_pct": np.nan,
            "ci_high_pct": np.nan,
        }

    point_base = merged[f"{metric_col}_base"].mean()
    point_prop = merged[f"{metric_col}_prop"].mean()
    point_imp = 100.0 * (point_base - point_prop) / point_base

    rng = np.random.default_rng(seed)
    vals = []
    groups = {t: merged[merged["track_key"] == t] for t in tracks}

    for _ in range(reps):
        sampled = rng.choice(tracks, size=len(tracks), replace=True)
        d = pd.concat([groups[t] for t in sampled], ignore_index=True)

        mb = d[f"{metric_col}_base"].mean()
        mp = d[f"{metric_col}_prop"].mean()

        if np.isfinite(mb) and abs(mb) > 1e-12:
            vals.append(100.0 * (mb - mp) / mb)

    vals = np.asarray(vals, dtype=np.float64)

    return {
        "n_tracks": len(tracks),
        "point_improvement_pct": point_imp,
        "ci_low_pct": float(np.quantile(vals, 0.025)),
        "ci_high_pct": float(np.quantile(vals, 0.975)),
    }

