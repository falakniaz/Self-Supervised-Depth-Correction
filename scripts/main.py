def bootstrap_ci(x, n_boot=800, ci=95, seed=0, stat_fn=np.mean):
    x = np.asarray(x, dtype=np.float64)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return np.nan, np.nan, np.nan

    rng = np.random.default_rng(seed)
    stats = []
    for _ in range(n_boot):
        samp = rng.choice(x, size=len(x), replace=True)
        stats.append(stat_fn(samp))
    stats = np.sort(stats)

    lo = np.percentile(stats, (100-ci)/2)
    hi = np.percentile(stats, 100-(100-ci)/2)
    mid = stat_fn(x)
    return mid, lo, hi

