def drop_lidar_points(velo_uvz, keep_ratio=0.3, seed=0):
    u,v,z = velo_uvz
    rng = np.random.default_rng(seed)
    m = u.shape[0]
    keep = rng.random(m) < keep_ratio
    return (u[keep], v[keep], z[keep])

