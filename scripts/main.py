def raw_depth_by_key(records):
    return {(r["track_key"], r["t"]): float(r["z_mean"]) for r in records}

def moving_average_depth(records, window=3):
    out = {}
    tracks = build_tracks(records)

    for _, tr in tracks.items():
        zs = pd.Series([r["z_mean"] for r in tr], dtype=float)
        sm = zs.rolling(window=window, center=True, min_periods=1).mean().to_numpy()
        for r, z in zip(tr, sm):
            out[(r["track_key"], r["t"])] = float(z)
    return out

def savgol_depth(records, window=5, polyorder=2):
    out = {}
    tracks = build_tracks(records)

    for _, tr in tracks.items():
        zs = np.asarray([r["z_mean"] for r in tr], dtype=np.float64)
        n = len(zs)
        w = min(window, n if n % 2 == 1 else n - 1)

        if w < 3 or w <= polyorder:
            sm = zs.copy()
        else:
            sm = savgol_filter(
                zs,
                window_length=w,
                polyorder=min(polyorder, w-1),
                mode="interp"
            )

        for r, z in zip(tr, sm):
            out[(r["track_key"], r["t"])] = float(z)
    return out

def kalman_depth(records, process_var=0.10):
    out = {}
    tracks = build_tracks(records)

    for _, tr in tracks.items():
        if not tr:
            continue

        dt = float(tr[0]["dt_default"])
        x = np.asarray([tr[0]["z_mean"], 0.0], dtype=np.float64)
        P = np.eye(2, dtype=np.float64) * 10.0

        F = np.asarray([[1.0, dt], [0.0, 1.0]], dtype=np.float64)
        H = np.asarray([[1.0, 0.0]], dtype=np.float64)

        q = process_var
        Q = q * np.asarray([
            [dt**4/4, dt**3/2],
            [dt**3/2, dt**2],
        ], dtype=np.float64)

        I = np.eye(2, dtype=np.float64)

        for r in tr:
            x = F @ x
            P = F @ P @ F.T + Q

            z_meas = float(r["z_mean"])
            R = np.asarray([[max(float(r["z_std"])**2, 1e-3)]], dtype=np.float64)

            y = np.asarray([z_meas]) - H @ x
            S = H @ P @ H.T + R
            K = P @ H.T @ np.linalg.inv(S)

            x = x + (K @ y).reshape(-1)
            P = (I - K @ H) @ P

            out[(r["track_key"], r["t"])] = float(x[0])

    return out

