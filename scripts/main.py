def plot_position_error(records_base, records_ref, top_k=5, min_points=5):
    from collections import defaultdict
    import numpy as np
    import matplotlib.pyplot as plt

    # Group by tid
    by_tid_base = defaultdict(list)
    by_tid_ref  = defaultdict(list)

    for r in records_base:
        by_tid_base[r["tid"]].append(r)
    for r in records_ref:
        by_tid_ref[r["tid"]].append(r)

    common_tids = sorted(set(by_tid_base.keys()) & set(by_tid_ref.keys()))
    print(f"[DEBUG] base tids={len(by_tid_base)}, ref tids={len(by_tid_ref)}, common={len(common_tids)}")

    if not common_tids:
        print("[ERROR] No common tids found.")
        return

    # pick top-k by baseline length
    lens = sorted([(tid, len(by_tid_base[tid])) for tid in common_tids],
                  key=lambda x: x[1], reverse=True)[:top_k]

    plt.figure(figsize=(9, 5))
    plotted_any = False

    for tid, _ in lens:
        b = sorted(by_tid_base[tid], key=lambda x: x["t"])
        r = sorted(by_tid_ref[tid],  key=lambda x: x["t"])

        n = min(len(b), len(r))
        if n < min_points:
            print(f"[DEBUG] Track {tid}: only n={n} points -> skipped")
            continue

        # time axis (use refined time or baseline time; both are fine after sorting)
        times = np.array([r[i]["t"] for i in range(n)], dtype=float)

        B = np.stack([b[i]["world_lidar"] for i in range(n)], axis=0).astype(float)
        R = np.stack([r[i]["world_ref"]   for i in range(n)], axis=0).astype(float)

