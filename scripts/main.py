def prepare_frame_batches(records_in):
    by_t = {}
    for r in records_in:
        by_t.setdefault(r["t"], []).append(r)

    batches = []
    for t in sorted(by_t):
        rs = by_t[t]
        X = np.stack([make_numeric_features(r) for r in rs]).astype(np.float32)
        C = np.asarray([r["cls"] for r in rs], dtype=np.int64)
        batches.append((
            torch.from_numpy(X).to(DEVICE),
            torch.from_numpy(C).to(DEVICE),
        ))
    return batches


def measure_inference_ms_per_frame(model, frame_batches, repeats=20, warmup=20):
    model.eval()
    if not frame_batches:
        return np.nan

    with torch.no_grad():
        for X, C in frame_batches[:min(warmup, len(frame_batches))]:
            _ = model(X, C)

    if torch.cuda.is_available():
        torch.cuda.synchronize()

    elapsed = []
    with torch.no_grad():
        for _ in range(repeats):
            if torch.cuda.is_available():
                torch.cuda.synchronize()
            t0 = time.perf_counter()
            for X, C in frame_batches:
                _ = model(X, C)
            if torch.cuda.is_available():
                torch.cuda.synchronize()
            elapsed.append(time.perf_counter() - t0)

    return 1000.0 * float(np.mean(elapsed)) / len(frame_batches)

