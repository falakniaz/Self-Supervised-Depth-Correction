# 7. GLOBAL-frame refinement used for FAIR evaluation of all variants
# ------------------------------------------------------------
@torch.no_grad()
def refine_records_global(model, records_in):
    model.eval()
    refined = []

    T_np = np.asarray(T_cam2_imu, dtype=np.float64)

    for r in records_in:
        x = torch.from_numpy(make_numeric_features(r)).float().to(DEVICE).unsqueeze(0)
        cls = torch.tensor([r["cls"]], dtype=torch.long, device=DEVICE)
        dz = float(model(x, cls)[0].detach().cpu())
        z_ref = float(r["z_mean"]) + dz

        # Same global transform for EVERY variant at evaluation time.
        uvzw = np.array([
            float(r["cx"]) * z_ref,
            float(r["cy"]) * z_ref,
            z_ref,
            1.0,
        ], dtype=np.float64)

        imu_h = T_np @ uvzw
        x_imu, y_imu, z_imu = imu_h[:3]

        yaw = float(r["yaw"])
        cy = np.cos(yaw)
        sy = np.sin(yaw)

        rel_enu = np.array([
            cy * x_imu - sy * y_imu,
            sy * x_imu + cy * y_imu,
            z_imu,
        ], dtype=np.float64)

        world_ref = np.asarray(r["ego_enu"], dtype=np.float64) + rel_enu

        rr = dict(r)
        rr["dz"] = dz
        rr["z_ref"] = z_ref
        rr["world_ref"] = world_ref.astype(np.float32)
        refined.append(rr)

    return refined

